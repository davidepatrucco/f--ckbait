// Genera il contenuto di brand-config.js (classic script) da un brand.json.
// Consumato da popup (script tag), content script (content_scripts) e service
// worker (importScripts). Espone globalThis.__BRAND__ (solo dati non sensibili).

export function brandConfigRuntime(cfg) {
    const t = cfg.tokens || {};
    const colors = t.colors || {};
    return {
        apiBrand: cfg.apiBrand,
        displayName: cfg.displayName,
        storeName: cfg.storeName || cfg.displayName,
        tagline: cfg.tagline || '',
        wordmark: cfg.wordmark || { pre: '', accent: cfg.displayName || '' },
        primaryAction: cfg.primaryAction || 'summarize',
        heroMetric: cfg.heroMetric || 'time_saved',
        tokens: {
            colors: {
                primary: colors.primary,
                primary700: colors.primary700 || colors.primary,
                black: colors.black || '#0D1117',
                white: colors.white || '#FFFFFF',
                gray100: colors.gray100 || '#F2F4F7',
                mint: colors.mint || '#22C55E',
                red: colors.red || '#EF4444'
            },
            radius: t.radius || '12px',
            shadowSm: t.shadowSm || '0 2px 6px rgba(0,0,0,0.08)',
            shadowMd: t.shadowMd || '0 8px 24px rgba(0,0,0,0.12)',
            fontSans: t.fontSans || "-apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif"
        }
    };
}

export function generateBrandConfigJs(cfg) {
    const runtime = brandConfigRuntime(cfg);
    return `// GENERATED by scripts/build-brand.mjs from brands/${cfg.id}/brand.json — do not edit by hand.
(function () {
  var BRAND = ${JSON.stringify(runtime, null, 2)};
  if (typeof globalThis !== 'undefined') globalThis.__BRAND__ = BRAND;
})();
`;
}
